export function getIllustration(id: IllustrationId): IllustrationDefinition {
  const item = ILLUSTRATION_REGISTRY[id];
  if (!item) {
    throw new Error(`Unknown Great Homes illustration ID: ${id}`);
  }
  return item;
}

export function listIllustrationsByFamily(family: string): IllustrationDefinition[] {
  return Object.values(ILLUSTRATION_REGISTRY).filter((i) => i.family === family);
}
